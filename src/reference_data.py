def download(spec: ReferenceSpec, session: requests.Session | None = None) -> ReferenceSpec:
    """Fetch one dataset. Leaves `status` at not_downloaded on any failure."""
    REFERENCE_DIR.mkdir(parents=True, exist_ok=True)
    out_path = REFERENCE_DIR / spec.filename
    sess = session or requests.Session()

    try:
        resp = sess.get(spec.url, timeout=120)
        resp.raise_for_status()
    except Exception as exc:  # network, DNS, egress policy, 404
        spec.note = (spec.note + " " if spec.note else "") + f"download failed: {exc}"
        return spec

    out_path.write_bytes(resp.content)

    import pandas as pd

    df = pd.read_csv(out_path, low_memory=False)
    spec.status = "downloaded"
    spec.row_count = len(df)
    spec.columns = df.shape[1]
    return spec


def main() -> list[ReferenceSpec]:
    session = requests.Session()
    specs = [download(spec, session) for spec in REFERENCE_DATASETS]

    ok = [s for s in specs if s.status == "downloaded"]
    for s in specs:
        count = f"{s.row_count:,} rows" if s.row_count else "-"
        print(f"  [{s.status:14s}] {s.filename:<32} {count}")
    print(f"\n{len(ok)}/{len(specs)} reference datasets downloaded, "
          f"{sum(s.row_count or 0 for s in ok):,} rows total")
    return specs


if __name__ == "__main__":
    sys.exit(0 if main() else 1)
