"""
Reference datasets: twelve outside markets, all real, all fetchable without
an account.

Why this module exists
----------------------
`src/data_loader.py` targets the ten datasets originally scoped for this
project. Eight of them are gated (Kaggle auth, Kilts Center academic
registration, a Dataverse WAF) and stay undownloaded rather than faked. That
left the product estimating one market -- UK wholesale gift and homeware --
which is not the market most people asking "should I raise my price?" are
actually in.

This module adds markets that *are* reachable, by pulling from two public
archives that publish data over plain HTTPS with no credentials:

  - Rdatasets (vincentarelbundock/Rdatasets), the CSV mirror of datasets
    shipped with R packages -- which is where the published econometric
    panels live.
  - TidyTuesday (rfordatascience/tidytuesday), a weekly public data project.

How this roster was chosen
--------------------------
Not by hand-picking. Every CSV in both archives plus plotly/datasets --
5,960 files, 64,502,749 rows, 656,584,040 values -- was downloaded and
profiled for a numeric, positive price-like column alongside a numeric,
non-negative quantity-like column (see `python -m src.screen_archives`).
That screen returned 26 candidates, and each was then read against its own
documentation.

Three otherwise-perfect candidates were dropped for being simulated, and are
named here so nobody re-adds them:

  - ISLR/Carseats       "A simulated data set containing sales of child car
                        seats at 400 different stores."
  - Stat2Data/Grocery   "These data are not real, though they are simulated
                        to approximate an actual study."
  - sem/Kmenta          "The endogenous variables P and Q were generated by
                        simulation."

Simulated data would fit beautifully and mean nothing. What survived is
below: twelve datasets with named sources, most of them from published
papers.

Run: python -m src.reference_data
"""

